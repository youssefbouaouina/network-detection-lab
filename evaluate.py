#!/usr/bin/env python3
"""Evaluate Suricata alerts and Zeek logs against the frozen ground truth.

Inputs
  expected.yaml                        6 scenarios + 1 benign capture
  results/suricata/<id>/eve.json       Suricata output per PCAP
  results/zeek/<id>/*.log              Zeek output per PCAP

Outputs
  results/metrics.json
  results/RESULTS.md
  results/per_scenario.csv
"""

from __future__ import annotations

import csv
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
ZEEK_LOGS = ("conn.log", "http.log", "dns.log")


def load_yaml(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def read_alerts(path: Path) -> list[dict]:
    alerts = []
    if not path.exists():
        return alerts
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if event.get("event_type") != "alert":
            continue
        alert = event.get("alert") or {}
        alerts.append(
            {
                "signature": alert.get("signature", ""),
                "sid": alert.get("signature_id"),
                "severity": alert.get("severity"),
                "src": event.get("src_ip"),
                "dst": event.get("dest_ip"),
                "proto": event.get("proto"),
            }
        )
    return alerts


def zeek_counts(directory: Path) -> dict[str, int]:
    counts = {}
    for name in ZEEK_LOGS:
        path = directory / name
        if not path.exists():
            counts[name] = 0
            continue
        counts[name] = sum(
            1
            for line in path.read_text(encoding="utf-8", errors="replace").splitlines()
            if line and not line.startswith("#")
        )
    return counts


def evaluate(expected: dict) -> dict:
    rows = []
    for scenario in expected["scenarios"]:
        sid = scenario["id"]
        alerts = read_alerts(RESULTS / "suricata" / sid / "eve.json")
        wanted = set(scenario["expected_alerts"])
        matched = sorted({alert["signature"] for alert in alerts if alert["signature"] in wanted})
        rows.append(
            {
                "id": sid,
                "title": scenario["title"],
                "detected": bool(matched),
                "alerts": len(alerts),
                "matched": matched,
                "signatures": [alert["signature"] for alert in alerts],
                "zeek": zeek_counts(RESULTS / "zeek" / sid),
            }
        )

    benign_alerts = read_alerts(RESULTS / "suricata" / "S99_benign" / "eve.json")
    benign_zeek = zeek_counts(RESULTS / "zeek" / "S99_benign")

    detected = sum(1 for row in rows if row["detected"])
    total = len(rows)
    metrics = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "scenarios_total": total,
        "detected": detected,
        "recall": round(detected / total, 4) if total else None,
        "alerts_total": sum(row["alerts"] for row in rows),
        "benign_alerts": len(benign_alerts),
        "benign_signatures": [alert["signature"] for alert in benign_alerts],
        "benign_zeek": benign_zeek,
        "per_scenario": rows,
    }
    return metrics


def write(metrics: dict) -> None:
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")

    with (RESULTS / "per_scenario.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            ["id", "detected", "suricata_alerts", "matched", "zeek_conn", "zeek_http", "zeek_dns"]
        )
        for row in metrics["per_scenario"]:
            writer.writerow(
                [
                    row["id"],
                    row["detected"],
                    row["alerts"],
                    ";".join(row["matched"]),
                    row["zeek"]["conn.log"],
                    row["zeek"]["http.log"],
                    row["zeek"]["dns.log"],
                ]
            )

    lines = [
        "# Results — network-detection-lab",
        "",
        f"Generated by `python evaluate.py` at {metrics['generated_at']} (UTC) from the",
        "Suricata and Zeek output in this directory.",
        "",
        "## Headline",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Scenarios detected | **{metrics['detected']}/{metrics['scenarios_total']}** "
        f"({metrics['recall']:.1%}) |",
        f"| Suricata alerts across malicious captures | {metrics['alerts_total']} |",
        f"| Alerts on the benign capture | **{metrics['benign_alerts']}** |",
        "",
        "## Per scenario",
        "",
        "| ID | Scenario | Detected | Suricata alerts | Rule(s) | Zeek conn/http/dns |",
        "|---|---|---|---|---|---|",
    ]
    for row in metrics["per_scenario"]:
        rules = ", ".join(f"`{name}`" for name in row["matched"]) or "—"
        zeek = row["zeek"]
        lines.append(
            f"| {row['id']} | {row['title']} | {'yes' if row['detected'] else 'no'} | "
            f"{row['alerts']} | {rules} | {zeek['conn.log']}/{zeek['http.log']}/{zeek['dns.log']} |"
        )

    lines += [
        "",
        "## Benign capture (false positives)",
        "",
        f"Alerts: **{metrics['benign_alerts']}**"
        + (
            " — " + ", ".join(f"`{name}`" for name in metrics["benign_signatures"])
            if metrics["benign_signatures"]
            else "."
        ),
        "",
        "Zeek parsed the benign capture as "
        f"{metrics['benign_zeek']['conn.log']} connections, "
        f"{metrics['benign_zeek']['http.log']} HTTP requests and "
        f"{metrics['benign_zeek']['dns.log']} DNS transactions.",
        "",
        "## Reproduction",
        "",
        "```bash",
        "python generate_pcaps.py",
        "bash scripts/run_lab.sh",
        "python evaluate.py",
        "```",
        "",
        "`generate_pcaps.py` only writes packets to files on 10.10.0.0/24; no packet is sent.",
        "Suricata and Zeek are pinned by the Ubuntu packages recorded in `results/`.",
        "",
    ]
    (RESULTS / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    expected = load_yaml(ROOT / "expected.yaml")
    metrics = evaluate(expected)
    write(metrics)
    print(
        f"detected {metrics['detected']}/{metrics['scenarios_total']} "
        f"benign alerts {metrics['benign_alerts']}"
    )
    gate = metrics["detected"] == metrics["scenarios_total"] and metrics["benign_alerts"] == 0
    return 0 if gate else 1


if __name__ == "__main__":
    sys.exit(main())
